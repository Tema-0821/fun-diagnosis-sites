export const GRADE_BANDS: readonly GradeBand[] = [
  { min: 90, titles: ["신화급 존재", "세계를 구한 전설", "이름조차 신성시되는 자"] },
  { min: 70, titles: ["전설로 남은 영웅", "이야기꾼들이 노래하는 인물", "왕국이 기억하는 이름"] },
  { min: 50, titles: ["마을을 지킨 영웅", "위기의 순간에 나서는 자", "믿음직한 동료"] },
  { min: 30, titles: ["떠돌이 모험가", "자유로운 방랑자", "새로운 길을 찾는 자"] },
  { min: 0, titles: ["여정을 시작한 견습생", "숨겨진 잠재력의 소유자", "이제 막 눈을 뜬 신참"] },
];

export function getGradeBand(score: number): GradeBand {
  return GRADE_BANDS.find((band) => score >= band.min) ?? GRADE_BANDS[GRADE_BANDS.length - 1];
}

