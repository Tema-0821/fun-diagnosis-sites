export interface GradeBand {
  min: number;
  titles: readonly string[];
}

// 점수 구간별 등급 타이틀 후보. 같은 구간이어도 시드에 따라 다른 타이틀이 뽑힌다.
export const GRADE_BANDS: readonly GradeBand[] = [
  { min: 90, titles: ["천생연분", "완벽 케미", "운명의 상대"] },
  { min: 70, titles: ["찰떡궁합", "말이 잘 통하는 사이", "죽이 잘 맞는 콤비"] },
  { min: 50, titles: ["티키타카 케미", "은근 잘 맞는 사이", "밀당의 고수"] },
  { min: 30, titles: ["다른 매력에 끌리는 사이", "성장형 케미", "노력하면 더 좋아지는 관계"] },
  { min: 0, titles: ["정반대의 매력", "예측불가 상성", "도전적인 조합"] },
];

export function getGradeBand(score: number): GradeBand {
  return GRADE_BANDS.find((band) => score >= band.min) ?? GRADE_BANDS[GRADE_BANDS.length - 1];
}

